    /// **Block 3 is exactly the machines whose answer the Version moves** — asked
    /// of the table, never listed by hand (SQ-0960).
    ///
    /// The whole point of the block is that a row per machine states the v1–v5
    /// screen as though it were the only one. So the test computes the set the
    /// same way the block does and checks the block prints that set and no other:
    /// a machine that stops moving must lose its rows, and one that starts must
    /// gain them, with no edit to either side.
    #[test]
    fn the_version_block_lists_every_machine_whose_screen_the_version_moves() {
        let moves = |n: u8| {
            (palette_for(n, Some(5)), period_look_for(n, Some(5)))
                != (palette_for(n, Some(6)), period_look_for(n, Some(6)))
        };
        let block = version_moves();
        for m in MACHINES {
            // ROWS, not mentions: the block's own legend names the IBM PC in
            // prose, and counting that would have made this case pass at three.
            let rows = block.lines().filter(|l| is_row(l, m.number, m.name)).count();
            if moves(m.number) {
                assert_eq!(rows, 2, "{} moves, so it needs a v1-v5 row AND a v6 row:\n{block}", m.name);
            } else {
                assert_eq!(rows, 0, "{} answers the same either way, so it has no row:\n{block}", m.name);
            }
        }
        // Non-vacuity: an empty block would satisfy every `== 0` above and say
        // nothing. Two machines move today, which is four rows.
        let moving: Vec<&str> =
            MACHINES.iter().filter(|m| moves(m.number)).map(|m| m.name).collect();
        assert_eq!(moving, ["Amiga", "IBM PC"], "the two machines Version 6 moved");
    }

    /// The two values that move are the ones a reader can ACT on: the graphics
    /// mode and the colour it draws.
    ///
    /// Sourced in [`crate::interpreter::palette_for`]'s own docs and corroborated
    /// there by a capture each: XZIP sends white to EGA attribute 7 and YZIP to
    /// 15, one entry apart, and every page and ink in the block is drawn through
    /// whichever it is. A block naming the machine and not the mode would be the
    /// same defect the block exists to fix.
    #[test]
    fn the_ibm_pcs_two_generations_print_their_mode_and_their_white() {
        let block = version_moves();
        let (early, late) = (row_of(&block, 6, "IBM PC", "v1-v5"), row_of(&block, 6, "IBM PC", "v6"));
        assert!(early.contains("EGA (XZIP)"), "the v1-v5 mode is named: {early}");
        assert!(late.contains("EGA (YZIP)"), "the v6 mode is named: {late}");
        // **The white is the one entry the two tables disagree on**, and it is
        // printed as the SCREEN gets it rather than as the adapter names it: EGA
        // attribute 7 is #AAAAAA, which the Z-machine's 15-bit colour space
        // truncates to 21/31 and replicates back as #ADADAD. Attribute 15 is
        // #FFFFFF, which survives the same round trip exactly — 31/31 — so the
        // move is visible in the output and not swallowed by it.
        assert!(early.contains("#ADADAD"), "…attribute 7, through 15-bit: {early}");
        assert!(late.contains("#FFFFFF"), "…against attribute 15: {late}");
        assert!(early.contains("#0000AD") && late.contains("#0000AD"), "the page does not move");
        // The caret moved on both machines, and is the pair reversed rather than a
        // colour (SQ-0947).
        assert!(late.contains("reversed cell"), "the v6 caret has no colour of its own: {late}");
        let amiga = row_of(&block, 4, "Amiga", "v1-v5");
        assert!(amiga.contains("block #FF7E1C"), "the Amiga's v1-v5 caret is its orange: {amiga}");
        assert!(
            row_of(&block, 4, "Amiga", "v6").contains("reversed cell"),
            "…and Version 6 reverses the pair instead:\n{block}"
        );
    }

