    /// A printed ROW for this machine, as against the prose that names it.
    fn is_row(line: &str, number: u8, name: &str) -> bool {
        line.trim_start().starts_with(&format!("{number}  ")) && line.contains(name)
    }

    fn row_of<'a>(block: &'a str, number: u8, name: &str, version: &str) -> &'a str {
        block
            .lines()
            .find(|l| is_row(l, number, name) && l.contains(version))
            .unwrap_or_else(|| panic!("no {name} {version} row:\n{block}"))
    }
