//! The 8×16 bitmap face v6 raster **text** is drawn with (SQ-0932).
//!
//! **Generated — do not hand-edit.** Every glyph here is transcribed from
//! `crates/app/assets/u_vga16-subset.bdf`, which carries the provenance and the
//! licence; `crates/app/assets/README.md` records where the font came from and
//! how to regenerate this table. The test at the bottom re-parses that BDF and
//! fails if the two ever disagree, so an edit made here and nowhere else cannot
//! survive the gate.
//!
//! ## Why this exists
//!
//! [`crate::render::bitfont`] drew every v6 raster character from an 8×8 master
//! nearest-row doubled into the cell — and the cell is 8×**16**
//! (`v6_layout::FONT_W`/`FONT_H`), so half its vertical resolution was duplicated
//! scanlines and no glyph had a descender below the baseline. This face is
//! natively 8×16: at the one cell size every production call site uses, it blits
//! **1:1**, no resampling on either axis.
//!
//! It is only the raster path's face. Hybrid draws text as terminal glyphs by
//! design (CLAUDE.md: "in hybrid, never rasterise what the game printed as a
//! character"), so it neither gains nor loses anything here.
//!
//! ## Text only — font 3 is deliberately NOT here
//!
//! The subset stops at letters: ASCII, Latin-1, `Œ`/`œ`, and the replacement
//! character. Box drawing, block elements and the cursor arrows are **Z-machine
//! font 3**, and they stay on [`crate::render::bitfont`]'s 8×8 masters.
//!
//! Font 3 is a graphics character set, not a typeface. Nothing a story prints as
//! text can reach `U+2500`; those codepoints exist in the raster path only
//! because `zvm::cpu::exec::font3_translate` maps font-3 codes onto them. So
//! drawing them from a VGA *text* font is a category error — and on the Amiga it
//! is the wrong machine's glyph twice over, since *Journey* ships its own 8×8
//! font-3 file (`Char.data`, byte-identical to *Beyond Zork*'s `Graphic.Data`)
//! and that is what a real Amiga drew its rules with.
//!
//! **It is also measurably not free.** Uni-VGA's `│` is TWO pixels wide — CP437's
//! authentic double-column vertical — where `font8x8`'s is one. Including it moved
//! Journey's frame border a pixel and failed
//! `v6_journey_prose_containment::journeys_frame_border_is_a_single_native_pixel_column`,
//! whose hairline reading later assertions depend on. v6 rule geometry is not this
//! quest's to change.
//!
//! ## Bit order — this differs from the 8×8 masters next door
//!
//! Rows are **MSB-leftmost**: bit 7 is column 0, bit 0 is column 7. That is
//! BDF's own order, and it matches [`blorb::bitmap_font::BitmapFont`], which is
//! how the Macintosh and Amiga disk fonts already parse (SQ-0911/SQ-0916) and
//! therefore how any future face arriving off a release disk will look.
//!
//! `font8x8` — the fallback in [`crate::render::bitfont`] — packs the **opposite**
//! way, LSB-leftmost. Both orders are live in that module, one per face, which is
//! exactly the sort of thing that reads as a typo six months from now: a glyph
//! sampled with the wrong rule comes out mirrored, not corrupt, so it still looks
//! like a font. Each path names its order at the point of use.

