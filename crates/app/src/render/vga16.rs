    /// no bearing arithmetic; a future font that is *not* uniform would trip the
    /// assertions here instead of being silently mis-transcribed.
    fn parse_bdf() -> Vec<(u32, [u8; 16])> {
        let mut out = Vec::new();
        let mut enc: Option<u32> = None;
        let mut rows: Option<Vec<u8>> = None;
        for line in BDF.lines() {
            let line = line.trim_end();
            if let Some(v) = line.strip_prefix("ENCODING ") {
                enc = Some(v.trim().parse().expect("an ENCODING is a number"));
            } else if let Some(v) = line.strip_prefix("BBX ") {
                assert_eq!(v.trim(), "8 16 0 -4", "the subset is a uniform 8x16 grid");
            } else if let Some(v) = line.strip_prefix("DWIDTH ") {
                assert_eq!(v.trim(), "8 0", "the subset is fixed-pitch at 8px");
            } else if line == "BITMAP" {
                rows = Some(Vec::new());
            } else if line == "ENDCHAR" {
                let rows = rows.take().expect("ENDCHAR follows a BITMAP");
                let enc = enc.take().expect("ENDCHAR follows an ENCODING");
                let rows: [u8; 16] = rows.try_into().expect("16 rows per glyph");
                out.push((enc, rows));
            } else if let Some(rows) = rows.as_mut() {
                rows.push(u8::from_str_radix(line, 16).expect("a bitmap row is one hex byte"));
            }
        }
        out
    }

    /// The generated table IS the BDF beside it. This is the whole guard against
    /// the two drifting: the table is derived data, and nothing else in the build
    /// would notice a hand-edit to it.
    #[test]
    fn the_table_matches_the_bdf_it_was_generated_from() {
        let parsed = parse_bdf();
        assert_eq!(parsed.len(), GLYPHS.len(), "the subset and the table hold different glyph counts");
        for (i, (&(tc, trows), &(pc, prows))) in GLYPHS.iter().zip(parsed.iter()).enumerate() {
            assert_eq!(tc, pc, "entry {i}: the table and the BDF disagree on which codepoint this is");
            assert_eq!(trows, prows, "U+{tc:04X}: the table's bitmap is not the BDF's");
        }
    }

    /// Sorted, because [`glyph`] binary-searches. A generator that emitted them
    /// in any other order would return `None` for real glyphs.
    #[test]
    fn the_table_is_sorted_and_has_no_duplicates() {
        for w in GLYPHS.windows(2) {
            assert!(w[0].0 < w[1].0, "U+{:04X} is not before U+{:04X}", w[0].0, w[1].0);
        }
    }

    /// The ranges `assets/README.md` promises, spot-checked at their edges so a
    /// regenerated subset that quietly dropped one is caught.
    #[test]
    fn the_promised_ranges_are_present() {
        for ch in [' ', '~', 'A', 'z', '0', '\u{00A0}', '\u{00FF}', 'Œ', 'œ', 'É', 'ß', '\u{FFFD}'] {
            assert!(glyph(ch).is_some(), "U+{:04X} is inside a promised range", ch as u32);
        }
        assert_eq!(GLYPHS.len(), 194, "the subset is the 194 glyphs README.md tabulates");
    }

    /// Font 3 is absent BY DESIGN, not by accident — see the module docs. This
    /// pins the decision so a later widening of the subset has to argue with a
    /// failing test rather than quietly move Journey's frame border.
    #[test]
    fn font_three_is_not_in_this_face_and_the_eight_row_chain_still_has_it() {
        let font3 = ('\u{2500}'..='\u{259F}').chain('\u{2190}'..='\u{2195}');
        for ch in font3 {
            assert!(glyph(ch).is_none(), "U+{:04X} is font 3 and must not be drawn from a text face", ch as u32);
        }
        for ch in ['\u{2500}', '\u{2502}', '\u{250C}', '\u{2588}', '\u{2591}', '\u{2190}', '\u{2195}'] {
            assert!(
                crate::render::bitfont::glyph_bits(ch).is_some(),
                "U+{:04X} must still be drawable from the 8x8 chain",
                ch as u32
            );
        }
    }

    /// A space is blank — the one glyph whose bitmap is knowable without looking
    /// it up, so a wholesale transcription error shows here.
    #[test]
    fn a_space_is_blank() {
        assert_eq!(glyph(' ').unwrap(), [0x00; 16], "space is blank");
    }

    /// MSB-leftmost, checked on a glyph that is not symmetric: `L` is a stem down
    /// the left with a foot along the bottom, so its upper rows must have their
    /// HIGH bits set. Read LSB-first the same bytes would draw a mirrored `⌐`
    /// shape and still look font-like, which is why this is pinned.
    #[test]
    fn rows_are_msb_leftmost() {
        let l = glyph('L').unwrap();
        let stem = l.iter().find(|&&r| r != 0).copied().expect("L is not blank");
        assert!(stem & 0x80 != 0 || stem & 0x40 != 0, "L's stem is at the LEFT: {stem:#04X}");
        let foot = l.iter().rev().find(|&&r| r != 0).copied().unwrap();
        assert!(foot.count_ones() > stem.count_ones(), "L's foot is wider than its stem");
    }
