/// The 8×16 bitmap for `ch`, or `None` when this face doesn't carry it.
///
/// A `None` is ordinary, not an error: the subset is text, and every font-3
/// codepoint is deliberately outside it. Callers fall back to
/// [`crate::render::bitfont`]'s 8×8 chain, which covers the rest.
pub fn glyph(ch: char) -> Option<[u8; 16]> {
    let key = ch as u32;
    GLYPHS.binary_search_by_key(&key, |&(c, _)| c).ok().map(|i| GLYPHS[i].1)
}

