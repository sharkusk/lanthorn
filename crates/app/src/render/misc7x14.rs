//! survive the gate.
//!
//! ## Why this exists
//!
//! The Macintosh's 7×15 body face (FONT 524, `mac/xzip.lst`) lives only on
//! gitignored commercial disk media, so a bare `.z6` run under `--interpreter 3`
//! has a Mac-shaped cell (SQ-1011) with nothing to draw it — and every disk
//! font is otherwise untestable in CI. This is a public-domain 7-wide face that
//! can stand in, and an embedded copy is the only way the face machinery is
//! reachable at all without a commercial fixture.
//!
//! This module is asset-and-table only; WHEN it draws is
//! [`crate::render::bitfont::blit_glyph_styled`]'s decision and documented there.
//! In one line: a cell exactly 7 wide and at least 14 tall, after the release's
//! own face has declined — so a Macintosh cell with no volume behind it.
//!
//! ## Not a substitute for everything 7-wide
//!
//! Only the Macintosh's 7×15 *body* face is a typeface this can stand in for.
//! Its 7×12 *alt* face (FONT 1033) is Z-machine **font 3** — box drawing, block
//! elements, cursor arrows — which must tile edge to edge, a constraint no text
//! font satisfies; see SQ-1017. This module carries no font-3 glyphs, exactly
//! like [`crate::render::vga16`] before it.
//!
//! ## Row width — 7, not 8
//!
//! Every glyph is `BBX 7 14 0 -2` / `DWIDTH 7 0`: 7 pixels wide, 14 tall. Each
//! row still fits one `u8`, MSB-leftmost (bit 7 is column 0 … bit 1 is column
//! 6), with the **low bit always unused** — that is BDF's own byte-padding
//! convention for a width that doesn't divide 8. A reader who assumes all 8
//! bits are significant will mirror or shift every glyph by reading column 7
//! as real pixel data instead of padding.
//!
//! ## Bit order
//!
//! Rows are **MSB-leftmost**, matching [`blorb::bitmap_font::BitmapFont`] and
//! [`crate::render::vga16`] — see that module's docs for why this is the
//! order any face arriving off a release disk will already be in.

